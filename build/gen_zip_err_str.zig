const std = @import("std");

const ErrEntry = struct { type_char: u8, desc: []const u8 };

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(gpa);
    if (args.len < 4) {
        std.debug.print("usage: {s} <zip.h> <zipint.h> <out.c>\n", .{args[0]});
        return error.BadUsage;
    }

    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(gpa,
        \\/* generated by build/gen_zip_err_str.zig from zip.h/zipint.h -- do not edit */
        \\#include "zipint.h"
        \\
        \\#define L ZIP_ET_LIBZIP
        \\#define N ZIP_ET_NONE
        \\#define S ZIP_ET_SYS
        \\#define Z ZIP_ET_ZLIB
        \\#define E ZIP_DETAIL_ET_ENTRY
        \\#define G ZIP_DETAIL_ET_GLOBAL
        \\
        \\const struct _zip_err_info _zip_err_str[] = {
        \\
    );
    try emit(gpa, &out, try parse(gpa, try readFile(io, gpa, args[1]), "ZIP_ER_"));
    try out.appendSlice(gpa, "};\n\nconst int _zip_err_str_count = sizeof(_zip_err_str)/sizeof(_zip_err_str[0]);\n\nconst struct _zip_err_info _zip_err_details[] = {\n");
    try emit(gpa, &out, try parse(gpa, try readFile(io, gpa, args[2]), "ZIP_ER_DETAIL_"));
    try out.appendSlice(gpa, "};\n\nconst int _zip_err_details_count = sizeof(_zip_err_details)/sizeof(_zip_err_details[0]);\n");

    const dest = args[3];
    if (std.fs.path.isAbsolute(dest)) {
        var f = try std.Io.Dir.createFileAbsolute(io, dest, .{});
        defer f.close(io);
        try f.writeStreamingAll(io, out.items);
    } else {
        try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = dest, .data = out.items });
    }
}

fn readFile(io: std.Io, gpa: std.mem.Allocator, path: []const u8) ![]u8 {
    return try std.Io.Dir.cwd().readFileAlloc(io, path, gpa, .limited(8 * 1024 * 1024));
}

fn emit(gpa: std.mem.Allocator, out: *std.ArrayList(u8), entries: []const ErrEntry) !void {
    for (entries) |e| {
        try out.appendSlice(gpa, "    { ");
        try out.append(gpa, e.type_char);
        try out.appendSlice(gpa, ", \"");
        try out.appendSlice(gpa, e.desc);
        try out.appendSlice(gpa, "\"},\n");
    }
}

fn parse(gpa: std.mem.Allocator, source: []const u8, prefix: []const u8) ![]const ErrEntry {
    var list: std.ArrayList(ErrEntry) = .empty;
    var lines = std.mem.splitScalar(u8, source, '\n');
    while (lines.next()) |raw| {
        var line = std.mem.trim(u8, raw, " \t\r");
        if (!std.mem.startsWith(u8, line, "#define ")) continue;
        line = line["#define ".len..];
        if (!std.mem.startsWith(u8, line, prefix)) continue;
        line = line[prefix.len..];

        const name_len = for (line, 0..) |ch, i| {
            if (!(std.ascii.isUpper(ch) or std.ascii.isDigit(ch) or ch == '_')) break i;
        } else line.len;
        if (name_len == 0) continue;

        var rest = std.mem.trimStart(u8, line[name_len..], " \t");
        const num_len = for (rest, 0..) |ch, i| {
            if (!std.ascii.isDigit(ch)) break i;
        } else rest.len;
        if (num_len == 0) continue;

        rest = std.mem.trimStart(u8, rest[num_len..], " \t");
        if (!std.mem.startsWith(u8, rest, "/*")) continue;
        const close = std.mem.indexOf(u8, rest[2..], "*/") orelse continue;
        const body = std.mem.trim(u8, rest[2..][0..close], " \t");
        if (body.len < 2) continue;

        const type_char = body[0];
        if (std.mem.indexOfScalar(u8, "LNSZEG", type_char) == null) continue;
        try list.append(gpa, .{
            .type_char = type_char,
            .desc = std.mem.trim(u8, body[1..], " \t"),
        });
    }
    return list.items;
}
